# 修改菜单文案后运行：perl font/make-font.pl /path/to/unifont-16.0.04.hex.gz
# 字库来源：https://unifoundry.com/pub/unifont/unifont-16.0.04/font-builds/unifont-16.0.04.hex.gz
use strict;
use warnings;
use Digest::SHA;
use FindBin qw($Bin);
use IO::Uncompress::Gunzip qw($GunzipError);

my $font_path = shift or die "Usage: perl make-font.pl unifont-16.0.04.hex.gz\n";
open my $archive, '<:raw', $font_path or die "$font_path: $!";
my $digest = Digest::SHA->new(256)->addfile($archive)->hexdigest;
die "Expected GNU Unifont 16.0.04\n" unless
    $digest eq 'f9c8c7802453f47be02677176aeac2342ee96d354fad7a26cedcce48e68e1d9f';
close $archive;

# 运行时的文件名、数值和截断标记也需要字形。
my %needed = map { $_ => 1 } (0x20 .. 0x7e, 0x2026, 0xfffd);
my $pkg = "$Bin/../../..";
my $loader = "$pkg/../QcomModulePkg/Application/LinuxLoader";
my @sources = ("$Bin/../AndroidToolsUi.c", "$Bin/../MenuScreen.c",
               (map { "$pkg/Application/$_/$_.c" } qw(RebootTools BLTools ArbTools)),
               (map { "$loader/$_.c" } qw(SuperFbMenu SuperFbTitle SuperFbAdvanced SuperFbBrowser SuperFbUsbMsd)));
for my $path (@sources) {
    open my $source, '<:encoding(UTF-8)', $path or die "$path: $!";
    while (<$source>) {
        while (/\bL"((?:[^"\\]|\\.)*)"/g) {
            my $text = $1;
            $text =~ s/\\[rnt]//g;
            $needed{ord($_)} = 1 for split //, $text;
        }
    }
    close $source;
}

my $font = IO::Uncompress::Gunzip->new($font_path) or die $GunzipError;
my %glyphs;
while (<$font>) {
    next unless /^([0-9A-F]+):([0-9A-F]+)\s*$/;
    my ($code, $bitmap) = (hex($1), $2);
    next unless $needed{$code};
    my $width = length($bitmap) / 4;
    die sprintf("Unsupported width at U+%04X\n", $code) unless $width == 8 || $width == 16;
    my $digits = $width / 4;
    my @rows = map { sprintf '0x%04X', hex($_) << (16 - $width) } ($bitmap =~ /(.{$digits})/g);
    $glyphs{$code} = sprintf("    { 0x%04X, %2u, {\n      %s,\n      %s } },\n",
                            $code, $width, join(', ', @rows[0..7]), join(', ', @rows[8..15]));
}
my @codes = sort { $a <=> $b } keys %needed;
for (@codes) {
    die sprintf("Missing glyph U+%04X\n", $_) unless exists $glyphs{$_};
}

open my $license_file, '<:raw', "$Bin/OFL.txt" or die $!;
my $license = do { local $/; <$license_file> };
$license =~ s/\r\n/\n/g;
close $license_file;

# 将许可和字形放在同一常量对象内，独立分发 EFI 文件时也保留字库许可。
open my $out, '>:raw', "$Bin/../MenuFont.h" or die $!;
print $out "/* GNU Unifont 16.0.04 subset. Generated by font/make-font.pl. SPDX-License-Identifier: OFL-1.1 */\n";
printf $out "STATIC CONST struct {\n  CHAR8      License[%u];\n  MENU_GLYPH Glyphs[%u];\n} mMenuFont = {\n",
            length($license) + 1, scalar @codes;
my @lines = split /\n/, $license;
for my $line (@lines) {
    $line =~ s/(["\\])/\\$1/g;
    $line = qq(  "$line\\n");
}
print $out join("\n", @lines), ",\n  {\n", (map { $glyphs{$_} } @codes), "  }\n};\n";
close $out or die $!;
